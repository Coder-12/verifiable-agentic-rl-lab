from src.tasks.countdown.verifier import (
    VerificationResult,
    VerificationStatus,
    verify_countdown_expression,
)


REWARD_MAPPING: dict[str, float] = {
    VerificationStatus.CORRECT.value: 1.0,
    VerificationStatus.WRONG_VALUE.value: 0.3,
    VerificationStatus.WRONG_NUMBERS.value: 0.05,
    VerificationStatus.EMPTY_EXPRESSION.value: 0.0,
    VerificationStatus.PARSE_ERROR.value: 0.0,
    VerificationStatus.UNSAFE_EXPRESSION.value: 0.0,
    VerificationStatus.DIVISION_BY_ZERO.value: 0.0,
}


def reward_from_verification_result(result: VerificationResult) -> float:
    """
    Maps a structured verification result to a scalar reward for RL training.

    Reward mapping:
    - 1.0: Completely correct.
    - 0.3: Uses the exact required numbers but reaches the wrong final value.
           This keeps signal on arithmetic structure without equating it to success.
    - 0.05: Valid parseable math but wrong number usage.
            This preserves a weak dense signal while strongly discouraging omitted
            or invented literals.
    - 0.0: Invalid, unsafe, empty, parse error, or division by zero.
    """
    return REWARD_MAPPING[result.reason.value]


def countdown_reward(
    expression: str,
    target: int,
    numbers: list[int]
) -> float:
    """
    End-to-end reward function for the Countdown task.
    
    Args:
        expression: The raw string expression generated by the model.
        target: The exact integer target to reach.
        numbers: The exact multiset of integers that must be used.
        
    Returns:
        A scalar float reward.
    """
    result = verify_countdown_expression(
        expression=expression,
        target=target,
        numbers=numbers,
    )
    
    return reward_from_verification_result(result)
