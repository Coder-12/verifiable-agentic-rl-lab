def format_countdown_prompt(numbers: list[int], target: int) -> str:
    """
    Formats the user prompt for a specific task.
    """
    return (
        f"Numbers: {numbers}\n"
        f"Target: {target}\n"
        f"Use exactly these numbers once each: {numbers}\n"
        "Do not introduce any other integer literals."
    )


def extract_answer(completion: str) -> Optional[str]:
    """
    Extracts the mathematical expression from the <answer>...</answer> tags.
    
    Args:
        completion: The raw text generated by the LLM.
        
    Returns:
        The extracted string if exactly one valid <answer> tag pair is found.
        None if tags are missing, malformed, or multiple tags exist.
    """
    # re.DOTALL allows the regex to match across newlines just in case
    pattern = r"<answer>(.*?)</answer>"
    matches = re.findall(pattern, completion, flags=re.DOTALL)
    
    # We strictly enforce that exactly ONE answer block exists.
    # If the model outputs 0 or 2+ answer blocks, it fails formatting.
    if len(matches) == 1:
        return matches[0].strip()
        
    return None
