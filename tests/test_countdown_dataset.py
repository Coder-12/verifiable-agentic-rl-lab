from src.tasks.countdown.dataset import generate_countdown_dataset
from src.tasks.countdown.verifier import verify_countdown_expression, VerificationStatus

def test_dataset_generation_structure_and_constraints():
    num_samples = 10
    dataset = generate_countdown_dataset(
        num_samples=num_samples,
        min_numbers=3,
        max_numbers=5,
        min_value=1,
        max_value=20
    )
    
    assert len(dataset) == num_samples
    
    for task in dataset:
        assert "numbers" in task
        assert "target" in task
        assert "expected_solution" in task
        
        # Check constraints
        assert 3 <= len(task["numbers"]) <= 5
        assert all(1 <= n <= 20 for n in task["numbers"])
        assert task["target"] > 0
        assert isinstance(task["target"], int)


def test_generated_tasks_are_solvable_by_verifier():
    """
    Closed-loop test: Proves that the expected_solution generated by the dataset
    actually passes our strict verifier.
    """
    dataset = generate_countdown_dataset(num_samples=20)
    
    for task in dataset:
        result = verify_countdown_expression(
            expression=task["expected_solution"],
            target=task["target"],
            numbers=task["numbers"]
        )
        
        # The generated solution must be perfectly correct according to our oracle
        assert result.is_valid is True, f"Failed task: {task}. Reason: {result.reason}"
        assert result.reason == VerificationStatus.CORRECT


def test_dataset_generation_uses_full_requested_size_range():
    dataset = generate_countdown_dataset(
        num_samples=200,
        min_numbers=3,
        max_numbers=5,
    )

    observed_sizes = {len(task["numbers"]) for task in dataset}
    assert observed_sizes == {3, 4, 5}
